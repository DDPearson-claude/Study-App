#!/usr/bin/env node
// tools/roster-export.mjs — writes src/roster-shipped.js: the roster records the game ships, cut to the converter's allow-list
// (src/roster-species.js ROSTER_KEYS; docs/loop/SPEC.md §13, M1 step 2). The game never imports docs/loop/roster.json (the built
// file would carry every research field); it imports this file, and validate-data's loop pass fails if it differs from a fresh export.
//
//   node tools/roster-export.mjs           write the file
//   node tools/roster-export.mjs --check   exit 1 if the file is not what an export writes now (validate-data runs exportText())
//
// SHIPPED is the roster fish the game ships at the current step: M1 step 2's eight roster fish on built plans, and M1 step 3a's three
// (the Kissmark Trout on the trout plan, the Thousandcast Pike on the pike's, the Hullkiss Lamprey on the lamprey plan). Each later step
// adds its own with the plan that carries it.
import fs from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { allowList } from '../src/roster-species.js';

export const SHIPPED = Object.freeze(['dusk_minnow', 'mossback_perch', 'likely_chub', 'overbold_bass', 'rustfin_sucker', 'milkeye_perch', 'weeping_carp', 'reedjaw_pike',
  'kissmark_trout', 'thousandcast_pike', 'hullkiss_lamprey']);
// LOST-TACKLE.md §4.2: the guests a found notebook brings to the Mossmere from a later water (shipped as records of their home water,
// `guestOf` set by data.js; never in SPECIES_LOOP or the Mossmere's list)
export const GUESTS = Object.freeze(['rosefleck_trout', 'rainglass_darter', 'nightbloom_carp']);
export const OUT_PATH = new URL('../src/roster-shipped.js', import.meta.url);
const ROSTER_PATH = new URL('../docs/loop/roster.json', import.meta.url);

/** The file's text for the roster as it stands (deterministic: SHIPPED's order, the allow-list's key order). */
export function exportText(roster = JSON.parse(fs.readFileSync(ROSTER_PATH, 'utf8'))) {
  const fish = [...SHIPPED, ...GUESTS].map((id) => {
    const f = roster.fish.find((x) => x.id === id);
    if (!f) throw new Error(`roster-export: ${id} is not in docs/loop/roster.json`);
    return allowList(f);
  });
  const waterNames = [...new Set(fish.flatMap((f) => f.water))];
  const waters = waterNames.map((n) => { const w = roster.waters.find((x) => x.name === n); return { name: n, existingLake: w?.existingLake ?? null }; });
  const body = JSON.stringify({ waters, fish }, null, 1).replace(/\n\s*/g, ' ');
  return [
    '// src/roster-shipped.js — GENERATED by tools/roster-export.mjs from docs/loop/roster.json; do not edit by hand.',
    "// The roster fish the game ships (M1 step 2's eight on built plans, M1 step 3a's three on theirs, the lost notebooks' three guests), each cut to the converter's allow-list",
    '// (src/roster-species.js ROSTER_KEYS). validate-data --loop fails if this file differs from a fresh export.',
    `export const ROSTER_SHIPPED = ${body};`,
    '',
  ].join('\n');
}

if (import.meta.url === pathToFileURL(process.argv[1] || '').href) {
  const text = exportText(), path = fileURLToPath(OUT_PATH);
  if (process.argv.includes('--check')) {
    const now = fs.existsSync(path) ? fs.readFileSync(path, 'utf8') : '';
    console.log(now === text ? 'roster-export --check: src/roster-shipped.js is current' : 'roster-export --check: src/roster-shipped.js is stale (run node tools/roster-export.mjs)');
    process.exit(now === text ? 0 : 1);
  }
  fs.writeFileSync(path, text);
  console.log(`roster-export: wrote src/roster-shipped.js (${SHIPPED.length + GUESTS.length} fish, ${text.length} bytes)`);
}
